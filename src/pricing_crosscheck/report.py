def _fmt(x: Any, digits: int = 2) -> str:
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        if math.isnan(x):
            return "-"
        if x == 0:
            return "0"
        return f"{x:.{digits}e}" if (abs(x) < 1e-3 or abs(x) >= 1e4) else f"{x:.{digits + 2}g}"
    return str(x)


def _md_table(header: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(_fmt(c) for c in r) + " |" for r in rows]
    return out


def price_summary_rows(summary: Table) -> list[list[Any]]:
    return [[r["instrument"], r["engine"], r["points"], r["not_available"], r["excluded"], r["compared"],
             r["disagreements"], r["median_abs_diff"], r["max_abs_diff"], r["max_diff_over_tol"], r["note"]]
            for r in summary.rows]


PRICE_HEADER = ["instrument", "engine", "points", "not available", "excluded", "compared", "disagreements",
                "median abs diff", "max abs diff", "max abs diff / tol", "note"]


def category_counts(dis: Table) -> list[list[Any]]:
    c = Counter((r["instrument"], r["engine"], r["category"]) for r in dis.rows)
    return [[i, e, cat, n] for (i, e, cat), n in sorted(c.items())]


GEQ_IDENTITIES = {"american_geq_european"}


def identity_rows(ids: Table) -> list[list[Any]]:
    """Per (identity, engine): points, failures, how many points are informative, and the
    largest violation (|lhs - rhs| for equalities, max(rhs - lhs, 0) for American >= European)."""
    agg: dict[tuple[str, str], list[Any]] = {}
    for r in ids.rows:
        a = agg.setdefault((r["identity"], r["engine"]), [0, 0, 0, 0, 0.0])
        a[0] += 1
        a[1] += 0 if r["passed"] else 1
        a[2] += 1 if r["informative"] else 0
        a[3] += 1 if "machine precision" in r["note"] else 0
        viol = max(r["rhs"] - r["lhs"], 0.0) if r["identity"] in GEQ_IDENTITIES else abs(r["residual"])
        a[4] = max(a[4], viol)
    return [[k[0], k[1], a[0], a[1], a[2], a[3], a[4]] for k, a in sorted(agg.items())]


IDENTITY_HEADER = ["identity", "engine", "points", "failed", "informative points",
                   "points at machine precision", "max violation"]


def order_rows(orders: Table) -> list[list[Any]]:
    return [[r["experiment"], r["instrument"], r["point_id"].split("|")[0] if r["instrument"] != "barrier"
             else r["point_id"].split("|")[0], r["point_id"], r["engine"], r["fitted_order"], r["last_abs_error"],
             r["measurable"]] for r in orders.rows]


def greek_rows(greeks: Table) -> list[list[Any]]:
    agg: dict[tuple[str, str, str], list[Any]] = {}
    for r in greeks.rows:
        a = agg.setdefault((r["instrument"], r["method"], r["greek"]), [0, 0, 0.0])
        a[0] += 1
        a[1] += 1 if r["disagree"] else 0
        a[2] = max(a[2], abs(r["diff"]))
    return [[k[0], k[1], k[2], a[0], a[1], a[2]] for k, a in sorted(agg.items())]


def summary_markdown(tables: dict[str, Table], profile: str) -> str:
    v = env.library_versions()
    lines = [f"# Results summary ({profile} profile)", "",
             "Generated by `python -m pricing_crosscheck run`. Do not edit by hand.", "",
             f"Content hash `{env.content_hash()}`. "
             + ", ".join(f"{k} {v[k]}" for k in ("QuantLib", "numpy", "scipy", "python", "platform")) + ".", ""]
    lines += ["## Prices against the reference", "",
              "Counts are grid points. `excluded`: American points where the reference uncertainty exceeds "
              "0.1 x tolerance (protocol section 5). `not available`: engine raised or returned a non-finite value.",
              ""]
    lines += _md_table(PRICE_HEADER, price_summary_rows(tables["summary"])) + [""]
    lines += ["## Disagreements by category (protocol section 11)", ""]
    lines += _md_table(["instrument", "engine", "category", "count"], category_counts(tables["disagreements"]))
    lines += [""]
    lines += ["## Identity checks (protocol section 9)", ""]
    lines += ["Max violation: |lhs - rhs| for equalities; max(European - American, 0) for American >= European. "
              "Points at machine precision or holding by construction are not informative (protocol section 9).",
              ""]
    lines += _md_table(IDENTITY_HEADER, identity_rows(tables["identities"])) + [""]
    lines += ["## Observed convergence orders (protocol section 10)", ""]
    lines += _md_table(["experiment", "instrument", "option/type", "point", "engine", "fitted order",
                        "abs error at finest level", "measurable"], order_rows(tables["orders"])) + [""]
    lines += ["## Greeks against the analytic formula (protocol section 8)", ""]
    lines += _md_table(["instrument", "method", "greek", "points", "disagreements", "max abs diff"],
                       greek_rows(tables["greeks"])) + [""]
    lines += ["## QuantLib Greeks and the Black-Scholes PDE identity", "",
              "Max over points of |theta + 0.5 sigma^2 S^2 gamma + (r - q) S delta - r V| / max term, using the "
              "engine's own value and Greeks. A value at rounding level means theta is consistent with being "
              "derived from that identity.", ""]
    mx: dict[tuple[str, str], float] = defaultdict(float)
    cnt: Counter = Counter()
    for r in tables["greeks_pde_identity"].rows:
        k = (r["instrument"], r["engine"])
        mx[k] = max(mx[k], abs(r["residual"]) / max(1.0, r["scale"]))
        cnt[k] += 1
    lines += _md_table(["instrument", "engine", "points", "max relative residual"],
                       [[k[0], k[1], cnt[k], mx[k]] for k in sorted(mx)]) + [""]
    lines += ["## Monte Carlo z-scores", "",
              "z = (engine - reference) / SE. Under an unbiased estimator about 4.6% of points have |z| > 2 and "
              "0.27% have |z| > 3.", ""]
    zrows = []
    by: dict[tuple[str, str], list[float]] = defaultdict(list)
    for r in tables["comparisons"].rows:
        if math.isfinite(r["z"]) and not r["excluded"]:
            by[(r["instrument"], r["engine"])].append(abs(r["z"]))
    for k, zs in sorted(by.items()):
        zrows.append([k[0], k[1], len(zs), sum(z > 2 for z in zs), sum(z > 3 for z in zs), sum(z > 4 for z in zs),
                      max(zs)])
    lines += _md_table(["instrument", "engine", "points with SE > 0", "|z| > 2", "|z| > 3", "|z| > 4", "max |z|"],
                       zrows) + [""]
    return "\n".join(lines) + "\n"


def readme_block(tables: dict[str, Table]) -> str:
    lines = [README_START, ""]
    lines += _md_table(PRICE_HEADER, price_summary_rows(tables["summary"]))
    lines += ["", "Disagreements by category:", ""]
    lines += _md_table(["instrument", "engine", "category", "count"], category_counts(tables["disagreements"]))
    lines += ["", README_END]
    return "\n".join(lines)


def update_readme(tables: dict[str, Table], path: Path) -> None:
    text = path.read_text(encoding=ENCODING)
    block = readme_block(tables)
    pattern = re.compile(re.escape(README_START) + ".*?" + re.escape(README_END), re.S)
    if not pattern.search(text):
        raise RuntimeError(f"{path} has no generated results block")
    path.write_text(pattern.sub(lambda m: block, text), encoding=ENCODING)


