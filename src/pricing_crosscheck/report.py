def _axes(ax, title: str, xlabel: str, ylabel: str) -> None:
    ax.set_title(title, color=INK, fontsize=10, loc="left")
    ax.set_xlabel(xlabel, color=MUTED, fontsize=9)
    ax.set_ylabel(ylabel, color=MUTED, fontsize=9)
    ax.tick_params(colors=MUTED, labelsize=8)
    ax.grid(True, color=GRID, linewidth=0.6)
    for s in ax.spines.values():
        s.set_color(GRID)


def _series(ax, x, y, i: int, label: str) -> None:
    ax.plot(x, y, color=SERIES[i % len(SERIES)], marker=MARKERS[i % len(MARKERS)], markersize=4, linewidth=1.6,
            label=label)


def charts(tables: dict[str, Table], fig_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"font.family": "DejaVu Sans", "svg.hashsalt": "pricing-crosscheck"})
    fig_dir.mkdir(parents=True, exist_ok=True)
    written = []
    conv = tables["convergence"].rows
    exp = tables["experiments"].rows

    def save(fig, name: str) -> None:
        path = fig_dir / name
        fig.savefig(path, dpi=130, bbox_inches="tight", metadata={"Software": None})
        plt.close(fig)
        written.append(path)

    # 1. Convergence of trees and PDE, European call at the first convergence point.
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
    first = conv[0]["point_id"]
    for ax, exp_name, title, xl in ((axes[0], "tree", "Trees, European call", "steps"),
                                    (axes[1], "pde", "PDE, European call", "space nodes = time steps")):
        i = 0
        for eng in ("ql_crr", "own_crr", "ql_fd", "ql_fd_damped", "own_pde"):
            pts = [r for r in conv if r["experiment"] == exp_name and r["instrument"] == "european"
                   and r["engine"] == eng and r["point_id"] == first and math.isfinite(r["error"])]
            if pts:
                _series(ax, [r["resolution"] for r in pts], [abs(r["error"]) for r in pts], i, eng)
                i += 1
        ax.set_xscale("log")
        ax.set_yscale("log")
        _axes(ax, title, xl, "|price - closed form|")
        ax.legend(fontsize=8, frameon=False)
    fig.suptitle(first, fontsize=8, color=MUTED, x=0.01, ha="left")
    save(fig, "convergence_european.png")

    # 2. Digital: strike alignment.
    fig, ax = plt.subplots(figsize=(5.5, 3.8))
    for i, eng in enumerate(("own_pde_aligned_smoothed", "own_pde_unaligned_pointwise", "ql_fd")):
        pts = [r for r in exp if r["experiment"] == "digital_strike_alignment" and r["engine"] == eng]
        _series(ax, [r["parameter"] for r in pts], [max(abs(r["error"]), 1e-16) for r in pts], i, eng)
    ax.set_xscale("log")
    ax.set_yscale("log")
    _axes(ax, "Digital call: PDE error vs grid", "space nodes = time steps", "|price - closed form|")
    ax.legend(fontsize=8, frameon=False)
    save(fig, "digital_strike_alignment.png")

    # 3. Barrier MC monitoring bias.
    fig, ax = plt.subplots(figsize=(5.5, 3.8))
    bpid = next((r["point_id"] for r in conv if r["experiment"] == "monitoring"), None)
    i = 0
    for eng in ("ql_mc", "own_mc"):
        for variant in ("uncorrected", "corrected"):
            pts = [r for r in conv if r["experiment"] == "monitoring" and r["engine"] == eng
                   and r["variant"] == variant and r["point_id"] == bpid]
            if pts:
                x = [r["resolution"] for r in pts]
                ax.errorbar(x, [r["error"] for r in pts], yerr=[2 * r["std_error"] for r in pts],
                            color=SERIES[i], marker=MARKERS[i], markersize=4, linewidth=1.4, capsize=2,
                            label=f"{eng}, {variant}")
                i += 1
    ax.axhline(0.0, color=MUTED, linewidth=0.8)
    ax.set_xscale("log")
    _axes(ax, "Barrier MC: error vs monitoring dates (bars: 2 SE)", "dates per year", "price - closed form")
    ax.legend(fontsize=8, frameon=False)
    if bpid:
        fig.suptitle(bpid, fontsize=8, color=MUTED, x=0.01, ha="left")
    save(fig, "barrier_monitoring.png")

    # 4. Bump-size sweep.
    sw = tables["greeks_sweep"].rows
    fig, axes = plt.subplots(1, 4, figsize=(13, 3.4))
    pids = sorted({r["point_id"] for r in sw if r["instrument"] == "european"})
    for ax, g in zip(axes, ("delta", "gamma", "vega", "theta")):
        for i, pid in enumerate(pids):
            pts = [r for r in sw if r["instrument"] == "european" and r["greek"] == g and r["point_id"] == pid]
            _series(ax, [r["eps"] for r in pts], [max(r["abs_error"], 1e-17) for r in pts], i, pid.split("|")[0])
        ax.set_xscale("log")
        ax.set_yscale("log")
        _axes(ax, f"{g}: central difference", "relative bump eps", "|bump - analytic|")
    axes[0].legend(fontsize=7, frameon=False)
    save(fig, "greeks_bump_sweep.png")

    # 5. LR even versus odd steps.
    fig, ax = plt.subplots(figsize=(5.5, 3.8))
    lr = [r for r in exp if r["experiment"] == "lr_even_odd"]
    for i, (name, parity) in enumerate((("odd steps", 1), ("even steps", 0))):
        pts = [r for r in lr if r["parameter"] % 2 == parity]
        _series(ax, [r["parameter"] for r in pts], [abs(r["error"]) for r in pts], i, name)
    ax.set_xscale("log")
    ax.set_yscale("log")
    _axes(ax, "QuantLib LR tree, European call", "steps", "|price - closed form|")
    ax.legend(fontsize=8, frameon=False)
    save(fig, "lr_even_odd.png")

    # 6. Disagreement map: engine x region label, counts (sequential single hue).
    dis = tables["disagreements"].rows
    comp = tables["comparisons"].rows
    labels = ["near_expiry", "near_zero_vol", "near_barrier", "deep_moneyness", "negative_rate", "none"]
    keys = sorted({(r["instrument"], r["engine"]) for r in dis})
    if keys:
        import numpy as np

        mat = np.zeros((len(keys), len(labels)))
        tot = np.zeros((len(keys), len(labels)))
        for r in comp:
            k = (r["instrument"], r["engine"])
            if k not in keys or r["excluded"] or r["status"] != "ok":
                continue
            labs = r["labels"].split(";") if r["labels"] else ["none"]
            for lab in labs:
                tot[keys.index(k), labels.index(lab)] += 1
                if r["disagree"]:
                    mat[keys.index(k), labels.index(lab)] += 1
        fig, ax = plt.subplots(figsize=(8, 0.35 * len(keys) + 1.6))
        from matplotlib.colors import LinearSegmentedColormap

        cmap = LinearSegmentedColormap.from_list("blue", ["#ffffff", "#cde2fb", "#6da7ec", "#2a78d6", "#104281"])
        frac = np.divide(mat, tot, out=np.zeros_like(mat), where=tot > 0)
        ax.imshow(frac, cmap=cmap, vmin=0, vmax=1, aspect="auto")
        for i in range(len(keys)):
            for j in range(len(labels)):
                if tot[i, j]:
                    ax.text(j, i, f"{int(mat[i, j])}/{int(tot[i, j])}", ha="center", va="center", fontsize=7,
                            color=INK if frac[i, j] < 0.6 else "#ffffff")
        ax.set_xticks(range(len(labels)), labels, rotation=30, ha="right", fontsize=8, color=MUTED)
        ax.set_yticks(range(len(keys)), [f"{a} / {b}" for a, b in keys], fontsize=8, color=MUTED)
        ax.set_title("Disagreements / compared points by region label (shade: fraction)", fontsize=10,
                     color=INK, loc="left")
        save(fig, "disagreement_map.png")
    return written


