              "2. up = ermqdt * pdash / pu is then 0/0 = NaN, and so is down; every node price is NaN.",
              "3. The payoff max(K - NaN, 0) is NaN, and `std::max(0.0, NaN)` in the exercise condition returns "
              "0, so all terminal values are 0 and the price is exactly 0, without an error.",
              "4. For calls (d2 > 0) pu rounds to exactly 1; all weight follows the all-up path, whose node price "
              "is finite because pow(NaN, 0) = 1, so deep in-the-money calls were priced correctly by accident.", "",
              f"Evidence: recomputing pu with the 1.43 formulas gives exactly 0 at all {len(lr_big)} points "
              f"({sum(1 for x in pu if x == 0.0)} of {len(pu)}); "
              "`results/investigations/lr_deep_itm_ql1.43.csv` (from `scripts/lr_deep_itm_mechanism.py`) shows "
              "that, over these points and controls at 1001, 2003 and 4005 steps, the wrong prices are exactly the "
              "put rows with pu = 0. Affected region: |d2| above "
