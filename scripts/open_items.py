"""Write docs/open_items.md: every disagreement classified 'not explained' in
results/full/disagreements.csv, plus the output of scripts/repro_lr_deep_itm.py.

Usage: python scripts/open_items.py
"""

import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pricing_crosscheck.results import read_table  # noqa: E402


def main() -> None:
    _, rows = read_table(ROOT / "results" / "full" / "disagreements.csv")
    groups = defaultdict(list)
    for r in rows:
        if r["category"] in ("not explained", "LSM bias, not explained", "MC bias, not explained"):
            groups[(r["instrument"], r["engine"], r["category"])].append(r)
    out = ["# Open items (Phase 1)", "",
           "Generated by `python scripts/open_items.py` from `results/full/disagreements.csv`. These disagreements "
           "were not explained by the refinement rules of protocol section 11. They are observed differences, "
           "not claims of bugs.", ""]
    for (inst, eng, cat), grp in sorted(groups.items()):
        out += [f"## {inst} / {eng}: {cat} ({len(grp)} points)", "",
                "| point | diff | diff at 2x | diff at 4x |", "|---|---|---|---|"]
        for r in grp:
            out.append(f"| {r['point_id']} | {float(r['diff0']):.4g} | {float(r['diff1']):.4g} | "
                       f"{float(r['diff2']):.4g} |")
        out.append("")
    repro = subprocess.run([sys.executable, str(ROOT / "scripts" / "repro_lr_deep_itm.py")],
                           capture_output=True, text=True, check=True).stdout
    out += ["## Reproduction: QuantLib LR tree, deep in-the-money put with small volatility", "",
            "Output of `python scripts/repro_lr_deep_itm.py` (zero rates, spot 100):", "", "```", repro.rstrip(),
            "```", "",
            "Observed: the LR engine returns 0 where the analytic engine and the CRR tree return the intrinsic value, "
            "when the strike is very many standard deviations from the spot. The mechanism has since been confirmed "
            "from the QuantLib 1.43 source and by recomputing the tree parameters (finding 8 in docs/findings.md); "
            "these points are no longer in the list above. The behaviour was changed upstream in QuantLib 1.44 "
            "(pull request 2729).", ""]
    (ROOT / "docs" / "open_items.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
